def read_games(path):
    if not path.is_file():
        raise FileNotFoundError(f"CSV not found: {path}")
    data = pd.read_csv(path)
    data.columns = data.columns.str.strip().str.lower().str.replace(" ", "_")
    required = {"season", "week", "home", "home_pts", "away", "away_pts", "completed"}
    if not required.issubset(data.columns):
        raise ValueError(f"Missing columns: {sorted(required - set(data.columns))}")
    for col in ("season", "week"):
        data[col] = pd.to_numeric(data[col], errors="raise").astype(int)
    for col in ("home", "away"):
        data[col] = data[col].astype(str).str.strip()
    data["completed"] = (
        data["completed"].astype(str).str.strip().str.lower()
        .isin(["1", "1.0", "true", "yes"])
    )
    for col in ("home_pts", "away_pts"):
        data[col] = pd.to_numeric(data[col], errors="coerce")
    scores = data.loc[data["completed"], ["home_pts", "away_pts"]].to_numpy()
    if not np.isfinite(scores).all() or np.any(scores < 0):
        raise ValueError("A completed game has invalid scores.")
    if "date" not in data:
        data["date"] = ""
    teams = sorted(set(data["home"]) | set(data["away"]))
    if len(teams) != 16:
        raise ValueError(f"Expected 16 teams, found {len(teams)}.")
    return data, teams


def season_totals(data, teams):
    index = {team: i for i, team in enumerate(teams)}
    m = len(teams)
    H = np.zeros((m, m))
    meetings = np.zeros((m, m))
    played = np.zeros(m)
    wins = np.zeros(m)
    for game in data.loc[data["completed"]].itertuples(index=False):
        i, j = index[game.home], index[game.away]
        S, T = game.home_pts, game.away_pts
        x = (S + 1) / (S + T + 2)
        value = 0.5 + 0.5 * np.sign(x - 0.5) * np.sqrt(abs(2 * x - 1))
        H[i, j] += value
        H[j, i] += 1 - value
        meetings[i, j] += 1
        meetings[j, i] += 1
        played[[i, j]] += 1
        if S > T:
            wins[i] += 1
        elif T > S:
            wins[j] += 1
        else:
            wins[[i, j]] += 0.5
    return H, meetings, played, wins


def ranking(data, teams, prior, w=1.0):
    if w <= 0:
        raise ValueError("w must be positive.")
    H, _, played, _ = season_totals(data, teams)
    A = (H + w * prior) / (played[:, None] + w * (len(teams) - 1))
    np.fill_diagonal(A, 0.0)
    r = np.full(len(teams), 1 / len(teams))
    for _ in range(200000):
        y = A @ r
        new = y / y.sum()
        error = np.linalg.norm(new - r, ord=1)
        r = new
        if error < 1e-13:
            break
    else:
        raise RuntimeError("Power iteration did not converge.")
    values = np.linalg.eigvals(A)
    order = np.argsort(np.abs(values))[::-1]
    leading = values[order[0]]
    if abs(leading.imag) > 1e-9 or leading.real <= 0:
        raise RuntimeError("Invalid Perron eigenvalue.")
    lam = float(leading.real)
    ratio = float(abs(values[order[1]]) / lam)
    assert np.allclose(A @ r, lam * r, atol=1e-10)
    return r, lam, ratio


def wielandt(m):
    P = np.zeros((m, m))
    P[np.arange(m - 1), np.arange(1, m)] = 1.0
    P[-1, :2] = 0.5
    return P


def primitive_exponent(P):
    m = len(P)
    S = (P > 0).astype(np.int64)
    B = np.eye(m, dtype=np.int64)
    for n in range(1, (m - 1) ** 2 + 2):
        B = (B @ S > 0).astype(np.int64)
        if B.all():
            return n
    raise ValueError("No positive power within Wielandt's bound.")


def outbreak_probability(N, K, R0):
    if not (1 <= K < N and R0 > 0):
        raise ValueError("Require 1 <= K < N and R0 > 0.")
    k = np.arange(1, K, dtype=float)
    log_rho = np.r_[0.0, np.cumsum(-np.log(R0) - np.log1p(-k / N))]
    peak = log_rho.max()
    return float(np.exp(-peak - np.log(np.exp(log_rho - peak).sum())))


def epidemic_system(N, K, R0, gamma=1.0, dt=0.005):
    if not (1 < K < N and min(R0, gamma, dt) > 0):
        raise ValueError("Invalid epidemic parameters.")
    n = np.arange(1, K, dtype=float)
    p = gamma * R0 * n * (1 - n / N) * dt
    q = gamma * n * dt
    if np.any(p + q > 1):
        raise ValueError("dt is too large.")
    L = np.diag(p + q) - np.diag(p[:-1], 1) - np.diag(q[1:], -1)
    e = np.linalg.solve(L, np.ones(K - 1))
    assert np.allclose(L @ e, np.ones(K - 1))
    return L, e


def simulate_epidemic(N=100, K=10, R0=1.5, gamma=1.0, dt=0.005, trials=100000):
    epidemic_system(N, K, R0, gamma, dt)
    rng = np.random.default_rng(SEED)
    ids = np.arange(trials)
    x = np.ones(trials, dtype=np.int64)
    times = np.zeros(trials, dtype=np.int64)
    while ids.size:
        p = gamma * R0 * x * (1 - x / N) * dt
        q = gamma * x * dt
        u = rng.random(ids.size)
        times[ids] += 1
        x = x + (u < p).astype(np.int64) - ((u >= p) & (u < p + q))
        alive = (x > 0) & (x < K)
        ids, x = ids[alive], x[alive]
    elapsed = times * dt
    return elapsed.mean(), elapsed.std(ddof=1) / np.sqrt(trials)


