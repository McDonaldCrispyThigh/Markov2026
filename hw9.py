# Commented out IPython magic to ensure Python compatibility.
# %matplotlib inline
import numpy as np
from scipy.linalg import expm
from scipy.optimize import brentq
import matplotlib.pyplot as plt

print("=== Problem 3(b) ===")
Q = np.array([[-2, 2, 0, 0],
              [1, -3, 2, 0],
              [0, 2, -4, 2],
              [0, 0, 3, -3]], float)
ev = np.sort(np.linalg.eigvals(Q).real)[::-1]
print("eigenvalues", np.round(ev, 4))
print(f"sum {ev.sum():.4f}, tr Q {np.trace(Q):.4f}")
lam2 = ev[1]
print(f"lambda2 {lam2:.4f}, 1/|lambda2| {1 / abs(lam2):.4f}")

print("\n=== Problem 3(c) ===")
pi = np.array([3, 6, 6, 4]) / 19
print("pi", np.round(pi, 4), "pi Q", np.round(pi @ Q, 12))
x0 = np.array([1, 0, 0, 0], float)

def x(t):
    return x0 @ expm(t * Q)

def TV(t):
    return 0.5 * np.abs(x(t) - pi).sum()

ts = np.linspace(0, 5, 501)
X = np.array([x(t) for t in ts])
tv = np.array([TV(t) for t in ts])

t01 = brentq(lambda t: TV(t) - 0.01, 0.01, 5)
print(f"TV = 0.01 at t = {t01:.4f}")
print(f"ln(100)/|lambda2| = {np.log(100) / abs(lam2):.4f}")
C = tv[-1] * np.exp(-lam2 * ts[-1])
print(f"TV(t) ~ C e^(lambda2 t), C = {C:.4f}, ln(100 C)/|lambda2| = {np.log(100 * C) / abs(lam2):.4f}")

fig, ax = plt.subplots(1, 2, figsize=(11, 4))
for i in range(4):
    ax[0].plot(ts, X[:, i], lw=2, label=f"$x_{i}(t)$")
    ax[0].axhline(pi[i], color=f"C{i}", ls="--", lw=1)
ax[0].set_xlabel("t (hours)")
ax[0].set_ylabel("probability")
ax[0].set_title(r"$\vec x(t)=\vec x(0)e^{tQ}$, dashed: $\pi_i$")
ax[0].legend()
ax[1].semilogy(ts, tv, lw=2, label="TV(t)")
ax[1].semilogy(ts, C * np.exp(lam2 * ts), "k--", label=rf"slope $\lambda_2={lam2:.3f}$")
ax[1].axhline(0.01, color="gray", lw=1)
ax[1].axvline(t01, color="gray", lw=1)
ax[1].set_xlabel("t (hours)")
ax[1].set_ylabel("TV distance")
ax[1].set_title("Convergence to $\\pi$")
ax[1].legend()
fig.tight_layout()
plt.show()