# Commented out IPython magic to ensure Python compatibility.
# %matplotlib inline
import numpy as np
from scipy import stats
import matplotlib.pyplot as plt

print("=== Problem 2(c) ===")
rng = np.random.default_rng(2026)
lam, mu, T = 12.0, 3.0, 500.0
rho = lam / mu

occ = np.zeros(100)
t, n, jumps = 0.0, 0, 0
while True:
    rate = lam + n * mu
    tau = rng.exponential(1 / rate)
    if t + tau >= T:
        occ[n] += T - t
        break
    occ[n] += tau
    t += tau
    n += 1 if rng.random() < lam / rate else -1
    jumps += 1

frac = occ / T
ns = np.arange(len(occ))
pmf = stats.poisson(rho).pmf(ns)
diff = np.abs(frac - pmf)
k = diff.argmax()
print(f"jumps {jumps}, total time {occ.sum():.4f}")
print(f"largest |frac - Poisson(4)| = {diff[k]:.4f} at n = {k} "
      f"(frac {frac[k]:.4f}, pmf {pmf[k]:.4f})")
print(f"time average of X_t {np.sum(ns * frac):.4f}  (rho = {rho:.0f})")

c = 0
while stats.poisson(rho).sf(c) > 0.01:
    c += 1
print(f"smallest c with P(X > c) <= 0.01: c = {c}, "
      f"P(X > {c - 1}) = {stats.poisson(rho).sf(c - 1):.4f}, P(X > {c}) = {stats.poisson(rho).sf(c):.4f}")
print(f"simulated fraction of time X > {c}: {frac[c + 1:].sum():.4f}")

m = 15
fig, ax = plt.subplots(figsize=(8, 4))
ax.bar(ns[:m] - 0.2, frac[:m], width=0.4, label="Gillespie: fraction of time")
ax.bar(ns[:m] + 0.2, pmf[:m], width=0.4, label="Poisson(4) pmf")
ax.set_xticks(ns[:m])
ax.set_xlabel("bikes out, n")
ax.set_ylabel("probability")
ax.set_title(f"M/M/$\\infty$ bike share, T = {T:.0f} h")
ax.legend()
fig.tight_layout()
plt.show()