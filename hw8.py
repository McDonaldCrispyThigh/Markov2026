import numpy as np
from scipy import stats, optimize
import matplotlib.pyplot as plt

rng = np.random.default_rng(2026)

print("=== Problem 2(c) ===")
W, T = 200_000, 5.0
q, r_star, r_sky = 0.4, 3.0, 2.0

emit_star = rng.poisson(r_star * T, W)
emit_sky = rng.poisson(r_sky * T, W)
d1_star = rng.binomial(emit_star, q)
d1_sky = rng.binomial(emit_sky, q)

d2_star = rng.poisson(q * r_star * T, W)
d2_sky = rng.poisson(q * r_sky * T, W)

for name, s, k in [("thinned", d1_star, d1_sky), ("direct", d2_star, d2_sky)]:
    tot = s + k
    print(f"{name:8s} star mean {s.mean():.4f} var {s.var(ddof=1):.4f} | "
          f"sky mean {k.mean():.4f} var {k.var(ddof=1):.4f} | "
          f"corr {np.corrcoef(s, k)[0, 1]:+.4f} | "
          f"total mean {tot.mean():.4f} var {tot.var(ddof=1):.4f} | "
          f"P(total=10) {np.mean(tot == 10):.4f}")
    sel = tot == 10
    print(f"{'':8s} windows with 10 detections: {sel.sum()}, "
          f"P(exactly 6 star) {np.mean(s[sel] == 6):.4f}")
print(f"Poisson(10): mean 10, var 10, P(N=10) {stats.poisson(10).pmf(10):.4f}")
print(f"Bin(10,0.6) pmf(6) = {stats.binom(10, 0.6).pmf(6):.4f}")

Ts = rng.exponential(1 / (q * r_star), W)
Tk = rng.exponential(1 / (q * r_sky), W)
star_first = Ts < Tk
first = np.minimum(Ts, Tk)
M = np.maximum(Ts, Tk)
print(f"P(star first) {star_first.mean():.4f}  (exact 0.6)")
print(f"P(star first, within 1 s) {np.mean(star_first & (first <= 1)):.4f}  "
      f"(exact {0.6 * (1 - np.exp(-2)):.4f})")
print(f"E[M] {M.mean():.4f}  (exact {19 / 12:.4f})")
print(f"corr(first time, star indicator) {np.corrcoef(first, star_first)[0, 1]:+.4f}  (exact 0)")

print("\n=== Problem 3(c) ===")
lam = lambda t: 12 + 8 * np.cos(np.pi * (t - 16) / 12)
lam_max, days = 20.0, 30
Tend = 24.0 * days

n_prop = rng.poisson(lam_max * Tend)
prop = np.sort(rng.uniform(0, Tend, n_prop))
keep = rng.uniform(size=n_prop) < lam(prop) / lam_max
t_ev = prop[keep]
print(f"proposals {n_prop}, kept {keep.sum()}, fraction kept {keep.mean():.4f}  (exact 0.6)")

day_idx = (t_ev // 24).astype(int)
hour_idx = (t_ev % 24).astype(int)
counts = np.zeros((days, 24), int)
np.add.at(counts, (day_idx, hour_idx), 1)
c34 = counts[:, 3]
print(f"3-4 am over 30 days: mean {c34.mean():.4f}, var {c34.var(ddof=1):.4f}  "
      f"(Poisson(4.091): mean 4.091, var 4.091)")

fig, ax = plt.subplots(figsize=(7, 4))
ax.bar(np.arange(24) + 0.5, counts.mean(axis=0), width=0.9, alpha=0.6,
       label="simulated mean arrivals per clock hour")
tt = np.linspace(0, 24, 500)
ax.plot(tt, lam(tt), "k", lw=2, label=r"true $\lambda(t)$")
ax.set_xlabel("hour of day")
ax.set_ylabel("arrivals per hour")
ax.set_xticks(range(0, 25, 2))
ax.set_title("ER arrivals by thinning, 30 days")
ax.legend()
fig.tight_layout()
plt.show()

n = len(t_ev)

def Lam(a, b, phi, T):
    return a * T + 12 * b / np.pi * (np.sin(np.pi * (T - phi) / 12) + np.sin(np.pi * phi / 12))

def negll(th):
    a, b, phi = th
    rate = a + b * np.cos(np.pi * (t_ev - phi) / 12)
    if np.any(rate <= 0):
        return np.inf
    return -(np.log(rate).sum() - Lam(a, b, phi, Tend))

res = optimize.minimize(negll, x0=[10, 5, 14], method="Nelder-Mead",
                        options={"xatol": 1e-8, "fatol": 1e-8, "maxiter": 20000})
a_hat, b_hat, phi_hat = res.x
ll_cos = -res.fun
ll_const = n * np.log(n / Tend) - n
print(f"MLE: a {a_hat:.4f}, b {b_hat:.4f}, phi {phi_hat:.4f}")
print(f"max loglik cosine {ll_cos:.2f}, constant rate n/T={n / Tend:.4f}: {ll_const:.2f}, "
      f"difference {ll_cos - ll_const:.2f}, LR stat 2*diff {2 * (ll_cos - ll_const):.2f}")