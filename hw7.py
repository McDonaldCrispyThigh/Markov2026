def group_stats(lambdas):
    n = len(lambdas)
    count = 1 << n
    time = np.zeros(count)
    last = np.zeros((count, n))
    for mask in range(1, count):
        indices = [i for i in range(n) if mask & (1 << i)]
        total = sum(lambdas[i] for i in indices)
        time[mask] = 1 / total
        for i in indices:
            weight = lambdas[i] / total
            remaining = mask - (1 << i)
            time[mask] = time[mask] + weight * time[remaining]
            if remaining == 0:
                last[mask, i] = last[mask, i] + weight
            else:
                last[mask] = last[mask] + weight * last[remaining]
    return time[-1], last[-1]


def inclusion_expectation(lambdas):
    total = 0.0
    for mask in range(1, 1 << len(lambdas)):
        subset_rate = sum(lambdas[i] for i in range(len(lambdas)) if mask & (1 << i))
        if mask.bit_count() % 2 == 1:
            total = total + 1 / subset_rate
        else:
            total = total - 1 / subset_rate
    return total


