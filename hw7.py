def autocorrelation_time(values):
    values = values - np.mean(values)
    n = len(values)
    ft = np.fft.rfft(values, n=2 * n)
    acf = np.fft.irfft(ft * np.conjugate(ft))[:n]
    acf = acf / acf[0]
    tau = 1.0
    for lag in range(1, min(n // 2, 20000), 2):
        pair = acf[lag] + acf[lag + 1]
        if pair <= 0:
            break
        tau = tau + 2 * pair
        if lag > 5 * tau:
            break
    return tau


def mcmc(step, T):
    result = np.zeros((T, 2))
    z = np.array([0.0, 0.0])
    value = log_posterior(z[0], z[1])
    accepted = 0
    for t in range(T):
        y = z + step * rng.normal(size=2)
        next_value = log_posterior(y[0], y[1])
        if np.log(rng.random()) < next_value - value:
            z = y
            value = next_value
            accepted = accepted + 1
        result[t] = z
    return result, accepted / T


