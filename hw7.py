def tv_distance(m):
    p = 4 / m
    bin_probs = np.zeros(m + 1)
    pois_probs = np.zeros(m + 1)
    bin_probs[0] = (1 - p)**m
    pois_probs[0] = math.exp(-4)
    for j in range(1, m + 1):
        bin_probs[j] = bin_probs[j - 1] * (m - j + 1) / j * p / (1 - p)
        pois_probs[j] = pois_probs[j - 1] * 4 / j
    tail = max(0.0, 1 - np.sum(pois_probs))
    return 0.5 * (np.sum(np.abs(bin_probs - pois_probs)) + tail)


